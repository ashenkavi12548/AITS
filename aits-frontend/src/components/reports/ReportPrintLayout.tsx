  animalName: 'Animal Name',
  farmName: 'Facility / Location',
  morningYield: 'Morning (L)',
  eveningYield: 'Evening (L)',
  totalYield: 'Total (L)',
  qualityStatus: 'Quality',
  recordedBy: 'Recorder / Verified By',
  caseDate: 'Case Date',
  diagnosis: 'Diagnosis / Condition',
  severity: 'Severity',
  treatmentStatus: 'Treatment Status',
  treatment: 'Treatment / Protocol',
  treatmentStartDate: 'Treatment Start',
  treatmentEndDate: 'Treatment End',
  veterinarian: 'Attending Vet',
  clinicalRemarks: 'Clinical Remarks',
  serviceDate: 'Service Date',
  breedingMethod: 'Method',
  technician: 'Technician',
  sireInfo: 'Sire / Straw',
  pregnancyStatus: 'Pregnancy',
  expectedCalvingDate: 'Due Date',
  calvingOutcome: 'Calving Outcome',
  calvingStatus: 'Calving Status',
  dateTime: 'Date & Time',
  eventType: 'Event Category',
  eventDescription: 'Event Audit Details',
  feedingSession: 'Session Shift',
  feedCategory: 'Feed Category',
  feedType: 'Feed Formula',
  actualQuantity: 'Intake (kg)',
  quantity: 'Quantity (kg)',
  unit: 'Unit',
