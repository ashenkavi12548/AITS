import React from 'react';
import { ReportDownloadRequest, ReportPreviewData } from '@/types/report.types';
import AitsLogo from '@/components/common/AitsLogo';
import { generateReportReferenceNumber } from '@/utils/report-export/report-reference';
import { formatNumber } from '@/utils/report.utils';

interface ReportPrintLayoutProps {
  request: ReportDownloadRequest;
  previewData: ReportPreviewData;
}

